--- Filter emojis by search term
local function filter_emojis(emojis, search)
    local results = {}
    if search == "" or search == ":" then
        return emojis
    end
    for _, emoji in ipairs(emojis) do
        if string.find(emoji.name, search, 1, true) then
            table.insert(results, emoji)
        end
    end
    return results
end

--- Get emoji by name
local function get_emoji_by_name(emojis, name)
    for _, emoji in ipairs(emojis) do
        if emoji.name == name then
            return emoji
        end
    end
    return nil
end

return {
    emojis = emojis,
    filter_emojis = filter_emojis,
    get_emoji_by_name = get_emoji_by_name,
}